@pytest.fixture(scope="session")
def semantic_context():
    assert os.path.exists(SEMANTIC_CONTEXT_PATH), (
        f"Semantic context not found: {SEMANTIC_CONTEXT_PATH}"
    )
    with open(SEMANTIC_CONTEXT_PATH) as f:
        return f.read()


@pytest.fixture(scope="session")
def db_path():
    path = _find_db()
    if path is None:
        pytest.skip(
            "AMEND.db not found. Run assemble_db.py --no-upload first, "
            "or download from gs://openamend-data/amend.db"
        )
    return path


@pytest.fixture(scope="session")
def llm_client():
    client, model = _make_client()
    return client, model


@pytest.fixture(scope="session")
def all_results():
    """Shared accumulator for per-case results, written to summary.json at session end."""
    return []


# ---------------------------------------------------------------------------
# Parametrized eval test
# ---------------------------------------------------------------------------

fixtures = _load_fixtures()


@pytest.mark.parametrize("case", fixtures, ids=[c["id"] for c in fixtures])
def test_eval_case(case, semantic_context, db_path, llm_client, all_results):
    client, model = llm_client
    question = case["question"]
    t0 = time.monotonic()

    # --- Generate SQL ---
    raw_response = _generate_sql(client, model, semantic_context, question)
    sql = _extract_sql(raw_response)

    # --- Hard assertions ---
    rows, cols, error = _run_sql(db_path, sql)

    hard_pass = True
    hard_failure_reason = None

    if case.get("assert_sql_runs", True) and error:
        hard_pass = False
        hard_failure_reason = f"SQL error: {error}"

    if hard_pass and case.get("assert_nonempty", True) and len(rows) == 0:
        hard_pass = False
        hard_failure_reason = "Query returned 0 rows"

    for pattern in case.get("assert_sql_not_contains", []):
        if re.search(pattern, sql, re.IGNORECASE):
            hard_pass = False
            hard_failure_reason = f"SQL contains forbidden pattern: {pattern}"
            break

    # --- LLM judge ---
    rubric = case.get("judge_rubric", "Score 1-5 based on correctness.")
    schema_excerpt = semantic_context[:4000]  # first 4k chars has the key join patterns
    judge_result = _judge_sql(client, model, question, sql, rubric, schema_excerpt)

    duration_ms = int((time.monotonic() - t0) * 1000)

    result = {
        "id": case["id"],
        "tags": case.get("tags", []),
        "passed_hard": hard_pass,
        "hard_failure_reason": hard_failure_reason,
        "judge_score": judge_result.get("score", 1),
        "judge_reason": judge_result.get("reason", ""),
        "judge_fatal": judge_result.get("fatal", False),
        "sql_generated": sql,
        "error": error,
        "duration_ms": duration_ms,
    }
    all_results.append(result)

    # Fail the test if hard assertions failed or judge says fatal
    assert hard_pass, (
        f"Hard assertion failed for '{case['id']}': {hard_failure_reason}\n"
        f"Generated SQL:\n{sql}"
    )
    assert not judge_result.get("fatal", False), (
        f"Judge flagged fatal error for '{case['id']}': {judge_result.get('reason')}\n"
        f"Generated SQL:\n{sql}"
    )


# ---------------------------------------------------------------------------
# Session teardown: write summary.json
# ---------------------------------------------------------------------------

@pytest.fixture(scope="session", autouse=True)
def write_summary(all_results):
    yield  # tests run here
    if not all_results:
        return

    os.makedirs(RESULTS_DIR, exist_ok=True)
    config = _load_config()

    total = len(all_results)
    hard_pass_count = sum(1 for r in all_results if r["passed_hard"])
    fatal_count = sum(1 for r in all_results if r["judge_fatal"])
    scores = [r["judge_score"] for r in all_results if r["judge_score"] is not None]
    mean_score = round(sum(scores) / len(scores), 2) if scores else None
    p50_score = sorted(scores)[len(scores) // 2] if scores else None

    summary = {
        "run_at": datetime.datetime.utcnow().isoformat() + "Z",
        "model": MODEL,
        "judge_model": MODEL,
        "semantic_context_hash": _semantic_context_hash(),
        "results": all_results,
        "summary": {
            "total": total,
            "hard_pass": hard_pass_count,
            "hard_pass_rate": round(hard_pass_count / total, 3) if total else 0,
            "fatal_failures": fatal_count,
            "mean_judge_score": mean_score,
            "p50_judge_score": p50_score,
        },
    }

    with open(SUMMARY_PATH, "w") as f:
        json.dump(summary, f, indent=2)

    print(f"\n=== Eval Summary ===")
    print(f"Hard pass: {hard_pass_count}/{total} ({summary['summary']['hard_pass_rate']:.0%})")
    print(f"Fatal failures: {fatal_count}")
    print(f"Mean judge score: {mean_score}/5")
    print(f"Results written to {SUMMARY_PATH}")

    # Apply CI thresholds
    min_hard_pass = config.get("fail_on_hard_pass_below", 0.80)
    max_fatal = config.get("fail_on_fatal_above", 0)

    assert summary["summary"]["hard_pass_rate"] >= min_hard_pass, (
        f"Hard pass rate {summary['summary']['hard_pass_rate']:.0%} < threshold {min_hard_pass:.0%}"
    )
    assert fatal_count <= max_fatal, (
        f"{fatal_count} fatal failure(s) exceed threshold of {max_fatal}"
    )
