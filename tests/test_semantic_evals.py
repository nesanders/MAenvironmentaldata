"""Semantic context evals for the AMEND AI Analysis feature.

Tests that the semantic context in docs/assets/db_semantic_context.txt
supports accurate SQL generation for common user questions.

Two-pass evaluation per case:
  1. Hard assertions: SQL runs, returns rows, avoids known anti-patterns
  2. LLM-as-judge: rubric scoring (1-5) via a second gpt-4o-mini call

Requires:
  - GITHUB_TOKEN env var with models:read scope (or OPENAI_API_KEY as fallback)
  - AMEND.db at get_data/AMEND.db or downloadable from GCS

Run with:
  pytest tests/test_semantic_evals.py -v

Results written to tests/eval_results/summary.json.
"""
import datetime
import hashlib
import json
import os
import re
import sqlite3
import time

import pytest
import yaml

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIXTURES_PATH = os.path.join(os.path.dirname(__file__), "eval_fixtures.yaml")
EVAL_CONFIG_PATH = os.path.join(os.path.dirname(__file__), "eval_config.yaml")
RESULTS_DIR = os.path.join(os.path.dirname(__file__), "eval_results")
SUMMARY_PATH = os.path.join(RESULTS_DIR, "summary.json")
SEMANTIC_CONTEXT_PATH = os.path.join(REPO_ROOT, "docs", "assets", "db_semantic_context.txt")
DB_CANDIDATES = [
    os.path.join(REPO_ROOT, "get_data", "AMEND.db"),
    os.path.join(REPO_ROOT, "AMEND.db"),
]

GITHUB_MODELS_BASE = "https://models.inference.ai.azure.com"
MODEL = "gpt-4o-mini"


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _load_fixtures():
    with open(FIXTURES_PATH) as f:
        return yaml.safe_load(f)


def _load_config():
    if os.path.exists(EVAL_CONFIG_PATH):
        with open(EVAL_CONFIG_PATH) as f:
            return yaml.safe_load(f) or {}
    return {}


def _find_db():
    for path in DB_CANDIDATES:
        if os.path.exists(path):
            return path
    return None


def _semantic_context_hash():
    with open(SEMANTIC_CONTEXT_PATH, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()[:12]


def _make_client():
    try:
        from openai import OpenAI
    except ImportError:
        pytest.skip("openai package not installed")

    github_token = os.environ.get("GITHUB_TOKEN")
    openai_key = os.environ.get("OPENAI_API_KEY")

    if github_token:
        return OpenAI(base_url=GITHUB_MODELS_BASE, api_key=github_token), MODEL
    elif openai_key:
        return OpenAI(api_key=openai_key), MODEL
    else:
        pytest.skip("No GITHUB_TOKEN or OPENAI_API_KEY set — skipping evals")


def _extract_sql(text):
    """Extract SQL from a markdown code block or return the raw text."""
    match = re.search(r"```(?:sql)?\s*\n(.*?)```", text, re.DOTALL | re.IGNORECASE)
    if match:
        return match.group(1).strip()
    # Fallback: strip any prose before SELECT/WITH
    match = re.search(r"((?:WITH|SELECT)\s.+)", text, re.DOTALL | re.IGNORECASE)
    if match:
        return match.group(1).strip()
    return text.strip()


def _generate_sql(client, model, semantic_context, question):
    response = client.chat.completions.create(
        model=model,
        temperature=0,
        max_tokens=800,
        messages=[
            {
                "role": "system",
                "content": (
                    "You are a SQLite expert. Given a question and database context, "
                    "return ONLY a SQLite SQL query that answers the question. "
                    "Wrap the SQL in a ```sql code block. No explanation."
                ),
            },
            {
                "role": "user",
                "content": f"Database context:\n{semantic_context}\n\nQuestion: {question}",
            },
        ],
    )
    return response.choices[0].message.content


def _judge_sql(client, model, question, sql, rubric, schema_excerpt):
    response = client.chat.completions.create(
        model=model,
        temperature=0,
        max_tokens=300,
        messages=[
            {
                "role": "system",
                "content": (
                    "You are evaluating SQL generated by an AI for correctness. "
                    "Score 1-5 using the rubric. Respond with JSON only:\n"
                    '{"score": <1-5>, "reason": "<one sentence>", "fatal": <true|false>}\n'
                    "fatal=true means the query returns wrong or misleading results "
                    "(wrong table, missing required filter, wrong join)."
                ),
            },
            {
                "role": "user",
                "content": (
                    f"Question: {question}\n\n"
                    f"Generated SQL:\n{sql}\n\n"
                    f"Rubric:\n{rubric}\n\n"
                    f"Relevant schema:\n{schema_excerpt}"
                ),
            },
        ],
    )
    raw = response.choices[0].message.content.strip()
    # Strip markdown code block if present
    raw = re.sub(r"```(?:json)?\s*\n?", "", raw).strip("`").strip()
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        return {"score": 1, "reason": f"Judge returned unparseable JSON: {raw[:200]}", "fatal": False}


def _run_sql(db_path, sql):
    con = sqlite3.connect(db_path)
    try:
        cursor = con.execute(sql)
        rows = cursor.fetchall()
        cols = [d[0] for d in cursor.description] if cursor.description else []
        return rows, cols, None
    except Exception as e:
        return [], [], str(e)
    finally:
        con.close()


